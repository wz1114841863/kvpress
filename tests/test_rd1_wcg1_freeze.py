def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def accepted_body():
    # Independent accepted mapping result pins the prepared input, not firtool's
    # raw-file representation. Use the real helper, not a fabricated body.
    helper = ROOT / HELPER_REL
    body = helper.read_text().split('"""', 2)[1].strip() + '\n'
    result = json.loads((ROOT / 'analysis/dc_wcg1_wrapper_mapping_retry_result_20261107.json').read_text())
    pin = result['input_side_summary']['gated']['file_sha256'][GATE + '.sv']
    assert hashlib.sha256(body.encode()).hexdigest() == pin
    return helper, body, pin


@pytest.mark.parametrize('representation', ['absent', 'canonical', 'generated', 'empty'])
def test_pinned_inline_representations_keep_hash_domains_separate(tmp_path, representation):
    helper, body, pin = accepted_body()
    modules = {}
    if representation != 'absent':
        emitted = tmp_path / (GATE + '.sv')
        text = body
        if representation == 'generated':
            text = '// Generated by CIRCT firtool-1.158.0\n' + body + '\n'
        elif representation == 'empty':
            text = header(body) + '\nendmodule\n'
        emitted.write_text(text)
        modules[GATE] = (emitted, text)
    text, evidence = FREEZE.verified_inline(modules, helper)
    assert text == body
    assert evidence['canonical_sha256'] == pin
    assert evidence['canonical_bytes'] == 342
    assert evidence['emitted'] == (representation != 'absent')
    if representation == 'generated':
        assert evidence['raw_emitted']['bytes'] == 381
        assert evidence['raw_emitted']['sha256'] == FREEZE.RAW_EMITTED_INLINE_SHA256
        assert evidence['raw_emitted']['sha256'] != pin


@pytest.mark.parametrize('old,new', [
    ('CKLNQD1BWP12T30P140LVT', 'CKLNQD2BWP12T30P140LVT'),
    ('.TE(1\'b0)', '.TE(1\'b1)'),
    ('.CP(clock)', '.CP(enable)'),
    ('.E(enable)', '.E(clock)'),
    ('.Q(gated_clock)', '.Q(clock)'),
    ('enable_low = enable', 'enable_low = 0'),
    ('endmodule', 'wire unexpected;\nendmodule'),
])
def test_emitted_semantic_mutation_is_rejected(tmp_path, old, new):
    helper, body, _ = accepted_body()
    emitted = tmp_path / (GATE + '.sv')
    text = body.replace(old, new)
    assert text != body
    emitted.write_text(text)
    with pytest.raises(AssertionError):
        FREEZE.verified_inline({GATE: (emitted, text)}, helper)


@pytest.mark.parametrize('prefix', ['wire unexpected;\n', '`define ALTER_GATE 1\n'])
def test_unexpected_inline_prefix_is_not_discarded(tmp_path, prefix):
    helper, body, _ = accepted_body()
    emitted = tmp_path / (GATE + '.sv')
    text = prefix + body
    emitted.write_text(text)
    with pytest.raises(AssertionError, match='before inline gate'):
        FREEZE.verified_inline({GATE: (emitted, text)}, helper)


def test_helper_drift_is_rejected_before_first_string_extraction(tmp_path):
    helper, _, _ = accepted_body()
    changed = tmp_path / 'changed.scala'
    changed.write_text('val unrelated = """wrong module"""\n' + helper.read_text())
    with pytest.raises(AssertionError, match='helper source drift'):
        FREEZE.verified_inline({}, changed)


def fixture_wrapper(gated):
    lines = ['module route_a_m2_p3_wrapper(input clock);', 'reg held;']
    fields = {
        'member': {'logical_position': 15, 'payload_ref': 64},
        'suffix': {'transaction_identity_request_id': 3, 'transaction_identity_incarnation': 2,
                   'payload_handle_or_address': 64, 'source_generation': 8, 'destination_endpoint': 3},
    }
    for kind, data in fields.items():
        for row in range(2304):
            if gated:
                prefix = kind + 'Word' + ('_' + str(row) if row else '')
            else:
                prefix = ('membershipEntries' if kind == 'member' else 'membershipPayloadBindings')
                prefix += '_{}_{}'.format(row // 64, row % 64)
            lines.extend('reg [{}:0] {}_{};'.format(width - 1, prefix, field)
                         for field, width in data.items())
    if gated:
        lines.extend('{} gate_{}(.clock(clock));'.format(GATE, n) for n in range(4608))
    return '\n'.join(lines + ['endmodule', ''])


