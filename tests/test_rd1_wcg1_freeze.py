def test_real_freeze_main_accepts_prepared_pin_and_preserves_all_other_inputs(freeze_tree):
    baseline, context, output = freeze_tree
    before = {str(p.relative_to(baseline)): digest(p) for p in baseline.rglob('*') if p.is_file()}
    FREEZE.main()
    record = json.loads((output / 'composition.json').read_text())
    assert record['route_file_count'] == 49
    assert record['unchanged_route_units'] == 47
    assert record['changed_compilation_units'] == [WRAPPER_REL]
    assert record['added_compilation_units'] == ['route_a_control_projection_split/' + GATE + '.sv']
    assert record['PM1'] is False and record['RD2'] is False
    assert record['reference_byte_equal_RD1'] is True
    _, body, pin = accepted_body()
    assert record['inline_sha256'] == pin
    assert (output / record['added_compilation_units'][0]).read_text() == body
    for name, sha in before.items():
        assert digest(baseline / name) == sha
        if name not in [WRAPPER_REL, 'route_a_control_projection_successor.f']:
            assert digest(output / name) == sha
    assert (context / 'exit_status').read_text() == '0\n'


@pytest.mark.parametrize('failure', ['old_hash_domain', 'native_body', 'reference_drift', 'helper_drift'])
def test_real_freeze_main_rejects_before_creating_output(freeze_tree, monkeypatch, failure):
    _, context, output = freeze_tree
    if failure == 'old_hash_domain':
        monkeypatch.setattr(FREEZE, 'CANONICAL_INLINE_SHA256', FREEZE.RAW_EMITTED_INLINE_SHA256)
    elif failure == 'native_body':
        path = context / 'split/gated' / (GATE + '.sv')
        path.write_text(path.read_text().replace(".TE(1'b0)", ".TE(1'b1)"))
    elif failure == 'reference_drift':
        path = context / 'split/reference/route_a_m2_p3_wrapper.sv'
        path.write_text(path.read_text() + '// unexpected reference change\n')
    else:
        path = context / 'workspace' / HELPER_REL
        path.write_text(path.read_text() + '// unexpected helper change\n')
    with pytest.raises(AssertionError):
        FREEZE.main()
    assert not output.exists()


def test_real_freeze_main_does_not_overwrite_an_existing_output(freeze_tree):
    _, _, output = freeze_tree
    output.mkdir()
    (output / 'keep').write_text('preserve failed or accepted inputs\n')
    with pytest.raises(AssertionError):
        FREEZE.main()
    assert (output / 'keep').read_text() == 'preserve failed or accepted inputs\n'
